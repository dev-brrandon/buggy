#!/bin/sh
set -eu

DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
OUT="$DIR/.env"

if [ -e "$OUT" ]; then
  echo "Refusing to overwrite $OUT" >&2
  exit 1
fi

random_password() {
  openssl rand -hex 32
}

cat > "$OUT" <<ENV
LEGIT_ASSISTANT_HTTP_PORT=18080
LEGIT_ASSISTANT_DB_NAME=legit_assistant
LEGIT_ASSISTANT_DB_ADMIN_PASSWORD=$(random_password)
LEGIT_ASSISTANT_POSTGRES_PASSWORD=$(random_password)
LEGIT_ASSISTANT_MIGRATOR_PASSWORD=$(random_password)
LEGIT_ASSISTANT_BUGGY_PRIMARY_OWNER_ACTOR_ID=ebabce45-f565-48f8-8ec6-7d15b9e7b885

LEGIT_ASSISTANT_PANEL_SERVICE_HMAC_KEY_B64=
LEGIT_ASSISTANT_PANEL_CONTEXT_HMAC_KEY_B64=
LEGIT_ASSISTANT_NETWORKCORE_HMAC_KEY_B64=
LEGIT_NETWORKCORE_ASSISTANT_AUTHORITY_URL=
LEGIT_ASSISTANT_NETWORKCORE_AUTHORITY_HMAC_KEY_B64=
LEGIT_ASSISTANT_INFERENCE_URL=
LEGIT_ASSISTANT_INFERENCE_MODEL=
LEGIT_ASSISTANT_INFERENCE_API_KEY=
LEGIT_ASSISTANT_INFERENCE_ALLOW_EXTERNAL=false
ENV
chmod 600 "$OUT"
echo "Created $OUT (mode 600)."
